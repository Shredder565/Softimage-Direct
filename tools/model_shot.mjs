// Visual check of modeling behaviour: sphere creation, point/edge/polygon modes, rectangle selection, manipulator.
import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--headless=new'] });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:4173/'); await p.waitForTimeout(800);
await p.evaluate(() => window.Application.run('NewScene'));
await p.evaluate(() => window.Application.run('CreatePrim', { PresetObj: 'Sphere' }));
await p.waitForTimeout(400);
await p.screenshot({ path: 'docs/screenshots/model-1-sphere.png' });
// find camera viewport rect (index 1: top-right)
const vm = await p.$('.vm canvas'); const bb = await vm.boundingBox();
const cam = { x: bb.x + bb.width * 0.5 + 1, y: bb.y, w: bb.width / 2 - 1, h: bb.height / 2 - 1 };
const cx = cam.x + cam.w / 2, cy = cam.y + cam.h / 2;
await p.mouse.move(cx, cy); await p.keyboard.press('f'); await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-1b-framed.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
await p.keyboard.press('t'); await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-2-points.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
await p.mouse.move(cam.x + 20, cam.y + 30); await p.mouse.down(); await p.mouse.move(cam.x + cam.w - 20, cy - 10, { steps: 5 }); await p.mouse.up();
await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-3-points-sel.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
console.log('points selected', await p.evaluate(() => window.Application.compSel?.points?.size));
await p.keyboard.press('v'); await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-4-translate.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
const before = await p.evaluate(() => Array.from(window.Application.selectedObjects[0].primitive.mesh().positions.slice(0, 6)));
await p.mouse.move(cx, cy - 40); await p.mouse.down(); await p.mouse.move(cx, cy - 100, { steps: 6 }); await p.mouse.up(); await p.waitForTimeout(200);
const after = await p.evaluate(() => Array.from(window.Application.selectedObjects[0].primitive.mesh().positions.slice(0, 6)));
console.log('moved', before.map(x => x.toFixed(2)).join(','), '->', after.map(x => x.toFixed(2)).join(','));
await p.screenshot({ path: 'docs/screenshots/model-5-moved.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
await p.keyboard.press('Escape');
await p.keyboard.press('y'); await p.waitForTimeout(100);
await p.mouse.click(cx - 40, cy + 30); await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-6-poly.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
console.log('polys selected', await p.evaluate(() => window.Application.compSel?.polygons?.size));
await p.keyboard.press('e'); await p.waitForTimeout(100);
await p.mouse.move(cx - 80, cy + 60); await p.mouse.down(); await p.mouse.move(cx + 80, cy + 75, { steps: 5 }); await p.mouse.up(); await p.waitForTimeout(200);
await p.screenshot({ path: 'docs/screenshots/model-7-edges.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
console.log('edges selected', await p.evaluate(() => window.Application.compSel?.edges?.size));
await p.keyboard.press('Escape'); await p.waitForTimeout(100);
await p.mouse.click(cam.x + 30, cam.y + cam.h - 30); await p.waitForTimeout(200);
console.log('selection after empty click', await p.evaluate(() => window.Application.selection.length));
await p.screenshot({ path: 'docs/screenshots/model-8-after-empty-click.png', clip: { x: cam.x, y: cam.y, width: cam.w, height: cam.h } });
console.log('errors', errs);
await b.close();

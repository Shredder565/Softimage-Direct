export interface CmdSpec {
  lang: Lang; name: string; pluginName: string; author: string; menuID: string; menuLabel: string; compiler: string;
  description: string; tooltip: string; keyAssign: boolean; noBatch: boolean; noLog: boolean; returnValue: boolean; undoRedo: boolean;
  args: { name: string; def: string; handler: number }[];
}
const isNum = (v: string) => /^-?\d+(\.\d+)?$/.test(v);
function defaultText(lang: Lang, v: string, forAdd: boolean): string {
  if (v === '') return lang === 'C#' && forAdd ? 'null' : '';
  const cpp = lang === 'Cpp';
  if (/^(true|false)$/i.test(v)) return lang === 'Python' ? (v.toLowerCase() === 'true' ? 'true' : 'false') : v.toLowerCase();
  if (isNum(v)) return cpp ? `${v}l` : v;
  if (/^".*"$/.test(v)) return cpp ? `L${v}` : v;
  return cpp ? `L"${v}"` : `"${v}"`;
}

/** The pieces of a generated plug-in for one command: include lines, registration lines, callbacks text. */
export function generateCommandCode(spec: CmdSpec): { includes: string; register: string; callbacks: string } {
  const { lang, name } = spec; const cpp = lang === 'Cpp', cs = lang === 'C#', py = lang === 'Python', vb = lang === 'VBScript';
  const hasMenu = spec.menuID !== '' && spec.menuID !== 'None';
  const menuName = `${name}_Menu`;
  const sc = py || vb ? '' : ';';
  const q = (s: string) => cpp ? `L"${s}"` : `"${s}"`;
  const includes = cpp ? ['#include <xsi_argument.h>', '#include <xsi_command.h>', ...(hasMenu ? ['#include <xsi_menu.h>'] : [])].join('\n') : '';
  const reg = [cpp ? `in_reg.RegisterCommand( L"${name}", L"${name}" );` : cs ? `in_reg.RegisterCommand( "${name}", "${name}" );` : lang === 'JScript' ? `in_reg.RegisterCommand( "${name}", "${name}" );` : `in_reg.RegisterCommand( "${name}", "${name}" )`];
  if (hasMenu) reg.push(cpp ? `in_reg.RegisterMenu( ${spec.menuID}, L"${menuName}", false, false );` : lang === 'JScript' || cs ? `in_reg.RegisterMenu( ${spec.menuID}, "${menuName}", false, false );` : `in_reg.RegisterMenu( ${spec.menuID}, "${menuName}", false, false )`);
  const argNames = spec.args.map(a => a.name);
  const L: string[] = [];
  const fn = (nm: string, params: string, body: string[], sub = false) => {
    if (cs) return;
    if (cpp) L.push(`XSIPLUGINCALLBACK CStatus ${nm}( ${params} )`, '{', ...body.map(x => '\t' + x), '}', '');
    else if (py) L.push(`def ${nm}( ${params} ):`, ...body.map(x => '\t' + x), '');
    else if (vb) L.push(`${sub ? 'Sub' : 'Function'} ${nm}( ${params} )`, ...body.map(x => '\t' + x), `End ${sub ? 'Sub' : 'Function'}`, '');
    else L.push(`function ${nm}( ${params} )`, '{', ...body.map(x => '\t' + x), '}', '');
  };
  // ---- Init
  const I: string[] = [];
  const flag = (cap: string, on: boolean) => cpp ? `oCmd.SetFlag( siSupportsKeyAssignment, ${on} );`.replace('siSupportsKeyAssignment', cap) : py ? `oCmd.SetFlag( constants.${cap}, ${on ? 'true' : 'false'} )` : `oCmd.SetFlag( ${cap}, ${on} )${sc}`;
  if (cpp) I.push('Context ctxt( in_ctxt );', 'Command oCmd;', 'oCmd = ctxt.GetSource();', `oCmd.PutDescription( ${q(spec.description)} );`);
  else if (py) I.push('oCmd = in_ctxt.Source', `oCmd.Description = ${q(spec.description)}`);
  else if (vb) I.push('Set oCmd = in_ctxt.Source', `oCmd.Description = ${q(spec.description)}`);
  else I.push('var oCmd = in_ctxt.Source;', `oCmd.Description = ${q(spec.description)};`);
  if (spec.tooltip !== '') I.push(cpp ? `oCmd.PutTooltip( ${q(spec.tooltip)} );` : `oCmd.Tooltip = ${q(spec.tooltip)}${sc}`);
  if (!spec.keyAssign) I.push(flag('siSupportsKeyAssignment', false));
  if (spec.noBatch) I.push(flag('siCannotBeUsedInBatch', true));
  if (spec.noLog) I.push(flag('siNoLogging', true));
  I.push(cpp ? `oCmd.EnableReturnValue( ${spec.returnValue} );` : `oCmd.ReturnValue = ${py ? (spec.returnValue ? 'true' : 'false') : spec.returnValue}${sc}`);
  if (spec.args.length) {
    I.push(cpp ? 'ArgumentArray oArgs = oCmd.GetArguments();' : py ? 'oArgs = oCmd.Arguments' : vb ? 'Set oArgs = oCmd.Arguments' : 'var oArgs = oCmd.Arguments;');
    for (const a of spec.args) {
      const d = defaultText(lang, a.def, a.handler === 0);
      if (a.handler > 0) I.push(`oArgs.AddWithHandler( ${q(a.name)}, ${q(HANDLERS[a.handler])}${d !== '' ? ', ' + d : ''} )${py || vb ? '' : ';'}`);
      else {
        const parts = [q(a.name)]; if (!cpp) parts.push(cs ? 'siEmpty' : py ? 'constants.siArgumentInput' : 'siArgumentInput'); if (d !== '') parts.push(d);
        I.push(`oArgs.Add( ${parts.join(', ')} )${py || vb ? '' : ';'}`);
      }
    }
  }
  I.push(cpp ? 'return CStatus::OK;' : py ? 'return true' : vb ? `${name}_Init = true` : 'return true;');
  fn(`${name}_Init`, cpp ? 'CRef& in_ctxt' : 'in_ctxt', I);
  // ---- Execute
  const E: string[] = [];
  const logLine = cpp ? `Application().LogMessage( L"${name}_Execute called", siVerboseMsg );` : py ? `XSIApp.LogMessage( "${name}_Execute called", constants.siVerbose )` : vb ? `LogMessage "${name}_Execute called", siVerbose` : `Application.LogMessage( "${name}_Execute called", siVerbose );`;
  if (cpp) {
    E.push('Context ctxt( in_ctxt );', 'CValueArray args = ctxt.GetAttribute( L"Arguments" );');
    argNames.forEach((n, i) => E.push(`CValue ${n} = args[${i}];`));
  }
  E.push(logLine, `${COMMENT[lang]} TODO: Put your command implementation here.`);
  if (cpp && spec.returnValue) E.push('// ctxt.PutAttribute( L"ReturnValue", CValue( true ) ); // example of setting the return value', '// return CStatus::Fail; // on failure');
  if (cpp && spec.undoRedo) E.push('static LONG s_undoId = 0;', 'CValueArray undoData; undoData.Add( ++s_undoId );', 'ctxt.PutAttribute( L"UndoRedoData", undoData );', 'Application().LogMessage( L"Stored undo id " + CString( s_undoId ) );');
  E.push(cpp ? 'return CStatus::OK;' : py ? 'return true' : vb ? (spec.returnValue ? `${name}_Execute = true` : '') : 'return true;');
  const eParams = cpp ? 'CRef& in_ctxt' : argNames.join(', ');
  fn(`${name}_Execute`, eParams, E.filter(x => x !== ''), vb && !spec.returnValue);
  if (cpp && spec.undoRedo) for (const [suffix, text] of [['Undo', 'undo'], ['Redo', 'redo'], ['TermUndoRedo', 'term']]) fn(`${name}_${suffix}`, 'CRef& in_ctxt', ['Context ctxt( in_ctxt );', `Application().LogMessage( L"${name}_${suffix} (${text}) id " + CString( (LONG)ctxt.GetAttribute( L"UndoRedoData" ) ) );`, 'return CStatus::OK;']);
  // ---- Menu
  if (hasMenu) {
    const label = spec.menuLabel !== '' ? spec.menuLabel : name;
    if (cpp) fn(`${menuName}_Init`, 'CRef& in_ctxt', ['Context ctxt( in_ctxt );', 'Menu oMenu;', 'oMenu = ctxt.GetSource();', 'MenuItem oNewItem;', `oMenu.AddCommandItem( L"${label}", L"${name}", oNewItem );`, 'return CStatus::OK;']);
    else fn(`${menuName}_Init`, 'in_ctxt', py ? ['oMenu = in_ctxt.Source', `oMenu.AddCommandItem( "${label}", "${name}" )`, 'return true'] : vb ? ['Set oMenu = in_ctxt.Source', `oMenu.AddCommandItem "${label}", "${name}"`, `${menuName}_Init = true`] : ['var oMenu = in_ctxt.Source;', `oMenu.AddCommandItem( "${label}", "${name}" );`, 'return true;']);
  }
  let callbacks = L.join('\n').replace(/\n+$/, '\n');
  if (cs) callbacks = csClasses(spec, hasMenu, menuName);
  return { includes, register: reg.join('\n'), callbacks };
}

function csClasses(spec: CmdSpec, hasMenu: boolean, menuName: string): string {
  const { name } = spec; const L: string[] = [];
  L.push(`public class ${name}`, '{', '\tpublic bool Init( XSIOM.Context in_ctxt )', '\t{', '\t\tXSIOM.Command oCmd = (XSIOM.Command)in_ctxt.Source;', `\t\toCmd.Description = "${spec.description}";`);
  if (spec.tooltip !== '') L.push(`\t\toCmd.Tooltip = "${spec.tooltip}";`);
  if (!spec.keyAssign) L.push('\t\toCmd.SetFlag( siSupportsKeyAssignment, false );');
  if (spec.noBatch) L.push('\t\toCmd.SetFlag( siCannotBeUsedInBatch, true );');
  if (spec.noLog) L.push('\t\toCmd.SetFlag( siNoLogging, true );');
  L.push(`\t\toCmd.ReturnValue = ${spec.returnValue};`);
  if (spec.args.length) { L.push('\t\tXSIOM.ArgumentCollection oArgs = oCmd.Arguments;'); for (const a of spec.args) L.push(a.handler > 0 ? `\t\toArgs.AddWithHandler( "${a.name}", "${HANDLERS[a.handler]}", null );` : `\t\toArgs.Add( "${a.name}", siEmpty, null );`); }
  L.push('\t\treturn true;', '\t}', '\tpublic bool Execute( XSIOM.Context in_ctxt )', '\t{', `\t\tXSIOM.Application.LogMessage( "${name}_Execute called" );`, '\t\t// TODO: Put your command implementation here.', '\t\treturn true;', '\t}', '}');
  if (hasMenu) L.push('', `public class ${menuName}`, '{', '\tpublic bool Init( XSIOM.Context in_ctxt )', '\t{', '\t\tXSIOM.Menu oMenu = (XSIOM.Menu)in_ctxt.Source;', `\t\toMenu.AddCommandItem( "${spec.menuLabel !== '' ? spec.menuLabel : name}", "${name}" );`, '\t\treturn true;', '\t}', '}');
  return L.join('\n') + '\n';
}


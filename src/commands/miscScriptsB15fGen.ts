export type Lang = 'VBScript' | 'JScript' | 'Python' | 'PerlScript' | 'Cpp' | 'C#';
export const HANDLERS = ['', 'AnimatableParameters', 'Collection', 'SingleObj', 'Frame', 'FrameRate', 'MarkedParameters'];
export const HANDLER_LABELS = ['None', 'Animatable Marked Parameters', 'Collection/Selection', 'SingleObj', 'Frame', 'Frame Rate', 'Marked Parameters'];

const COMMENT: Record<string, string> = { VBScript: "'", JScript: '//', Python: '#', PerlScript: '#', Cpp: '//', 'C#': '//' };
const SCRIPT_EXT: Record<string, string> = { VBScript: '.vbs', JScript: '.js', Python: '.py', PerlScript: '.pls', Cpp: '.cpp', 'C#': '.cs' };
export const scriptExt = (lang: string) => SCRIPT_EXT[lang] ?? '.vbs';
export const regComment = (lang: string) => (COMMENT[lang] ?? "'") + 'RegistrationInsertionPoint - do not remove this line';
export const isScript = (lang: string) => lang === 'VBScript' || lang === 'JScript' || lang === 'Python';

let menuIdCache: any[] | null = null;
export function resetMenuIdCache() { menuIdCache = null; }

export function standardIncludes(lang: string): string {
  switch (lang) {
    case 'Cpp': return ['xsi_application.h', 'xsi_context.h', 'xsi_pluginregistrar.h', 'xsi_status.h'].map(h => `#include <${h}>`).join('\n');
    case 'C#': return ['using System;', 'using XSIOM = Softimage.XSIOM;', 'using XSIMath = Softimage.XSIMath;', 'using XSIUtil = Softimage.XSIUtil;'].join('\n');
    case 'Python': return ['import win32com.client', 'from win32com.client import constants as c', 'null = None', 'false = 0', 'true = 1'].join('\n');
    default: return '';
  }
}

/** Header comment, includes, load callback (author, name, version 1.0, register code, insertion comment) and unload callback. */
export function generatePluginFile(w: any, lang: string, comment: string, includes: string, author: string, pluginName: string, registerCode: string, callbacks: string): string {
  const c = COMMENT[lang] ?? "'"; const L: string[] = [];
  const cpp = lang === 'Cpp', cs = lang === 'C#';
  L.push(`${c} ${pluginName}`, `${c} Initial code generated by Softimage SDK Wizard`, `${c} Executed ${new Date().toLocaleDateString()} by ${w.GetCurrentUserLogin()}`);
  if (comment) L.push(...String(comment).split('\n').map(x => `${c} ${x}`));
  L.push(c + (cpp || cs ? ' Standard SDK plug-in header: this file is the plug-in entry point' : ' Standard script plug-in header: this file is the plug-in entry point'));
  const std = standardIncludes(lang); if (std) L.push(std);
  if (includes) L.push(includes);
  if (cpp) L.push('', 'using namespace XSI;');
  if (cs) L.push('', 'public class Base { /* sample base class */ }');
  L.push('');
  const q = (s: string) => cpp ? `L"${s}"` : `"${s}"`;
  const reg = String(registerCode ?? '').split('\n').filter(x => x !== '');
  const tail = '\t' + regComment(lang);
  if (cs) L.push('public class XSIPlugin : Base', '{', '\tpublic bool Load( XSIOM.PluginRegistrar in_reg )', '\t{', `\t\tin_reg.Author = ${q(author)};`, `\t\tin_reg.Name = ${q(pluginName)};`, '\t\tin_reg.Major = 1;', '\t\tin_reg.Minor = 0;', ...reg.map(x => '\t\t' + x), '\t' + tail, '\t\treturn true;', '\t}',
    '\tpublic bool Unload( XSIOM.PluginRegistrar in_reg )', '\t{', `\t\tXSIOM.Application.LogMessage( ${q(pluginName + ' has been unloaded.')} );`, '\t\treturn true;', '\t}', '}');
  else if (cpp) L.push('XSIPLUGINCALLBACK CStatus XSILoadPlugin( PluginRegistrar& in_reg )', '{', `\tin_reg.PutAuthor( ${q(author)} );`, `\tin_reg.PutName( ${q(pluginName)} );`, '\tin_reg.PutVersion( 1, 0 );', ...reg.map(x => '\t' + x), tail, '\treturn CStatus::OK;', '}', '',
    'XSIPLUGINCALLBACK CStatus XSIUnloadPlugin( const PluginRegistrar& in_reg )', '{', '\tCString strPluginName = in_reg.GetName();', '\tApplication().LogMessage( strPluginName + L" has been unloaded." );', '\treturn CStatus::OK;', '}');
  else if (lang === 'JScript') L.push('function XSILoadPlugin( in_reg )', '{', `\tin_reg.Author = ${q(author)};`, `\tin_reg.Name = ${q(pluginName)};`, '\tin_reg.Major = 1;', '\tin_reg.Minor = 0;', ...reg.map(x => '\t' + x), tail, '\treturn true;', '}', '',
    'function XSIUnloadPlugin( in_reg )', '{', `\tApplication.LogMessage( ${q(pluginName + ' has been unloaded.')}, siVerbose );`, '\treturn true;', '}');
  else if (lang === 'Python') L.push('def XSILoadPlugin( in_reg ):', `\tin_reg.Author = ${q(author)}`, `\tin_reg.Name = ${q(pluginName)}`, '\tin_reg.Major = 1', '\tin_reg.Minor = 0', ...reg.map(x => '\t' + x), tail, '\treturn true', '',
    'def XSIUnloadPlugin( in_reg ):', `\tXSIApp.LogMessage( ${q(pluginName + ' has been unloaded.')}, constants.siVerbose )`, '\treturn true');
  else L.push('Function XSILoadPlugin( in_reg )', `\tin_reg.Author = ${q(author)}`, `\tin_reg.Name = ${q(pluginName)}`, '\tin_reg.Major = 1', '\tin_reg.Minor = 0', ...reg.map(x => '\t' + x), tail, '\tXSILoadPlugin = true', 'End Function', '',
    'Function XSIUnloadPlugin( in_reg )', `\tLogMessage ${q(pluginName + ' has been unloaded.')}, siVerbose`, '\tXSIUnloadPlugin = true', 'End Function');
  if (callbacks) L.push('', callbacks);
  return L.map(x => x + '\n').join('');
}

const defaultTemplate = (kind: string): string => ({
  vcxproj: '<?xml version="1.0" encoding="utf-8"?>\n<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">\n  <PropertyGroup><ProjectName>%%projname%%</ProjectName></PropertyGroup>\n  <ItemGroup>\n%%cpp_files%%\n  </ItemGroup>\n</Project>\n',
  makefile: '# plug-in project %%projname%%\nSOURCES = %%cpp_files%%\n',
  csproj: '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><AssemblyName>%%projname%%</AssemblyName></PropertyGroup></Project>\n',
} as Record<string, string>)[kind];

/** Template text: the template file when it exists in the host file system, else this build's own minimal text. */
function templateText(w: any, file: string, kind: string): string {
  const p = w.GetTemplateFolder() + file;
  return hostFs.isFile(p) ? hostFs.readFile(p) : defaultTemplate(kind);
}

export function installWizardGenerators(w: any, app: App) {
  w.GetDefaultVCCompiler = () => 'VS2012';
  w.GetSupportedVCCompilerArray = () => ['Visual Studio 2010', 'VS2010', 'Visual Studio 2012', 'VS2012'];
  w.GetCppCompilerInfo = (v: any) => ({ name: v === 'VS2010' ? 'VS2010' : 'VS2012', projectExtension: '.vcxproj' });
  w.StandardIncludes = (lang: any) => standardIncludes(String(lang));
  w.CreateMenuIDArray = (): any[] => {
    if (menuIdCache) return menuIdCache;
    const out: any[] = ['None', -1];
    const decl = w.GetXSIDeclPath();
    if (decl && hostFs.isFile(decl)) {
      const text = hostFs.readFile(decl);
      const m = /enum\s+siMenuAnchorPoints\s*\{([\s\S]*?)\}/.exec(text);
      if (m) for (const line of m[1].split(/[\r\n,]+/)) {
        const mm = /^\s*(si\w+ID)\s*=\s*(-?\d+)/.exec(line);
        if (mm && !/obsolete/i.test(line) && mm[1] !== 'siMenuUndefinedID') out.push(mm[1], Number(mm[2]));
      }
    }
    return (menuIdCache = out);
  };
  w.GeneratePluginFile = (lang: any, comment: any, includes: any, author: any, pluginName: any, registerCode: any, callbacks: any) => {
    if ([lang, comment, includes, author, pluginName, registerCode, callbacks].some(x => x === undefined || x === null)) throw new Error('Invalid arg to GeneratePluginFile');
    return generatePluginFile(w, String(lang), String(comment), String(includes), String(author), String(pluginName), String(registerCode), String(callbacks));
  };
  /** -> bool. See the note: 7176 / 7196 / 7197 / 7198 / 7199. */
  w.WriteAndLoadScriptPlugin = (dir: any, rootName: any, lang: any, source: any, pluginName: any): boolean => {
    try { hostFs.ensureFolder(dir); } catch (e) { msgBox(app, 7176, errText(e)); return false; }
    const target = join(String(dir), String(rootName) + scriptExt(String(lang)));
    const other = pluginByName(app, String(pluginName));
    if (other && other.file.toLowerCase() !== target.toLowerCase()) { msgBox(app, 7196, other.file); return false; }
    if (hostFs.isFile(target)) {
      if (!msgBox(app, 7197, target, true)) return false;
      const st = miscState(app); const i = st.plugins.findIndex(p => p.file.toLowerCase() === target.toLowerCase()); if (i >= 0) st.plugins.splice(i, 1);   // unload that file
    }
    try { hostFs.writeFile(target, String(source)); } catch (e) { msgBox(app, 7198, errText(e)); return false; }
    try { app.run('ShowFileForEdit', { FileName: target }); } catch { /* no editor in a headless run */ }
    if (!loadPlugin(app, target, String(source), String(pluginName))) msgBox(app, 7199);   // still true
    return true;
  };
  w.GenerateCppProject = (dir: any, projName: any, cppText: any, compilerParam: any): boolean => {
    try { hostFs.ensureFolder(dir); } catch (e) { msgBox(app, 7176, errText(e)); return false; }
    const cpp = join(String(dir), `${projName}.cpp`);
    if (hostFs.isFile(cpp) && !msgBox(app, 7200, cpp, true)) return false;
    app.logMsg('info', 'Writing C++ file...');
    hostFs.writeFile(cpp, String(cppText));
    app.logMsg('info', 'Writing Visual Studio .vcxproj file...');
    const vs = String(compilerParam) === 'VS2010' ? 'VS2010' : 'VS2012';
    const tpl = templateText(w, vs === 'VS2012' ? 'Plugin.VS2012.vcxproj.template' : 'Plugin.vcxproj.template', 'vcxproj');
    const sub = (t: string) => t.replace(/%%projname%%/g, () => String(projName)).replace(/%%cpp_files%%/g, () => `    <ClCompile Include="${projName}.cpp" />`);
    hostFs.writeFile(join(String(dir), `${projName}.vcxproj`), sub(tpl));
    const mk = templateText(w, 'GNUmakefile.template', 'makefile').replace(/%%projname%%/g, () => String(projName)).replace(/%%cpp_files%%/g, () => String(projName));
    hostFs.writeFile(join(String(dir), 'GNUmakefile'), mk);
    try { app.run('ShowFileForEdit', { FileName: cpp }); } catch { /* headless */ }
    return true;   // nothing is compiled or loaded
  };
  w.GenerateCSProject = (dir: any, projName: any, csText: any): boolean => {
    try { hostFs.ensureFolder(dir); } catch (e) { msgBox(app, 7176, errText(e)); return false; }
    const cs = join(String(dir), `${projName}.cs`);
    if (hostFs.isFile(cs) && !msgBox(app, 7200, cs, true)) return false;
    app.logMsg('info', 'Writing C# file...');
    hostFs.writeFile(cs, String(csText));
    app.logMsg('info', 'Writing Visual Studio .csproj file...');
    hostFs.writeFile(join(String(dir), `${projName}.csproj`), templateText(w, 'Plugin.csproj.template', 'csproj').replace(/%%projname%%/g, () => String(projName)));
    try { app.run('ShowFileForEdit', { FileName: cs }); } catch { /* headless */ }
    return true;   // no Linux makefile
  };
}

